const schemas: Record<keyof typeof valid, z.ZodType> = {
  users: UserSchema,
  documents: DocumentSchema,
  chunks: ChunkSchema,
  conversations: ConversationSchema,
  messages: MessageSchema,
  turnTraces: TurnTraceSchema,
  tickets: TicketSchema,
  ticketEvents: TicketEventSchema,
  feedback: FeedbackSchema,
  evalRuns: EvalRunSchema,
  evalResults: EvalResultSchema,
  auditLog: AuditLogSchema,
  counters: CounterSchema,
  gapClusters: GapClusterSchema,
};

const issues = (key: keyof typeof valid, doc: unknown) => {
  const result = schemas[key].safeParse(doc);
  return result.success ? [] : result.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`);
};

describe('collection schemas accept a valid document', () => {
  it.each(Object.keys(valid) as (keyof typeof valid)[])('%s', (key) => {
    expect(issues(key, valid[key]())).toEqual([]);
  });
});

