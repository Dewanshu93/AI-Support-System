describe('collection schemas reject invalid documents', () => {
  it.each(invalidCases)('%s', (_name, key, mutate, expected) => {
    const doc = valid[key]() as Doc;
    mutate(doc);
    expect(issues(key, doc).join('\n')).toContain(expected);
  });

  it('accepts agents with queues and restricted hr_case tickets', () => {
    expect(issues('users', { ...valid.users(), role: 'agent', queues: ['it_hardware'] })).toEqual(
      [],
    );
    expect(
      issues('tickets', { ...valid.tickets(), restricted: true, queue: 'hr_case', domain: 'HR' }),
    ).toEqual([]);
  });
});
